abstract final class KoPresets {
  static const _kSeeded = 'koPresetsSeeded';

  // 처음 켤 때 한 번 (main 에서 GStorage.init 뒤에 부름)
  static void seedOnce() {
    try {
      final v = GStorage.setting.get(_kSeeded, defaultValue: 0);
      if (v is int && v >= 1) return;
      for (final p in workPresets) {
        apply(p);
      }
      GStorage.setting.put(_kSeeded, 1);
    } catch (_) {}
  }

  // 작품별 용어집·작품 기본 말투에 넣기. 이미 있는 줄(직접 고친 것 포함)은 그대로, 빠진 것만 더함
  static int apply(KoWorkPreset p) {
    var added = 0;
    var w = KoTr.works.where((e) => e.name == p.name).firstOrNull;
    if (w == null) {
      w = KoWork(name: p.name, detect: p.detect);
      KoTr.works.add(w);
    }
    final have = {for (final e in KoTr.parseGlossary(w.glossary)) e.key};
    final lines = w.glossary.trim().isEmpty ? <String>[] : w.glossary.trim().split('\n');
    for (final e in KoTr.parseGlossary(p.glossary)) {
      if (have.contains(e.key)) continue;
      lines.add('${e.key}=${e.value}');
      added++;
    }
    final det = w.detectWords.toSet();
    final more = p.detect.split(',').map((e) => e.trim()).where((e) => e.isNotEmpty && !det.contains(e));
    if (more.isNotEmpty) w.detect = [if (w.detect.trim().isNotEmpty) w.detect.trim(), ...more].join(', ');
    w.glossary = lines.join('\n');
    KoTr.saveWorks();

    final scope = KoVoice.workScope(p.name);
    final cur = KoVoice.book(scope);
    final names = {for (final c in cur.chars) c.ko};
    final pairs = {for (final r in cur.rels) r.pairKey};
    final pre = KoVoiceBook.parse(p.voice);
    final chars = [...cur.chars, ...pre.chars.where((c) => !names.contains(c.ko))];
    final rels = [...cur.rels, ...pre.rels.where((r) => !pairs.contains(r.pairKey))];
    added += (chars.length - cur.chars.length) + (rels.length - cur.rels.length);
    KoVoice.setText(scope, KoVoiceBook(chars, rels).format());
    return added;
  }

  // 기본 제공 말투로 되돌리기 (그 작품의 같은 인물·관계는 기본값으로 덮어씀)
  static void reset(KoWorkPreset p) {
    KoVoice.addAll(KoVoice.workScope(p.name), KoVoiceBook.parse(p.voice));
  }
}
